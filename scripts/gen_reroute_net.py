"""Generate scripts/reroute_net.py from scripts/route_base.py.

reroute_net.py keeps every track/via/zone of nets outside the rip set as fixed
obstacles and re-routes only the nets named in $RIP (comma list, e.g.
"+5V,/USB_D-,/USB_D+") with the route_base A* + rip-up.  Pin stubs are only
generated for ripped nets.  GND tracks, vias and the pours are kept.

Usage:  python3 scripts/gen_reroute_net.py
        RIP='+5V,/USB_D-,/USB_D+' python3 scripts/reroute_net.py SRC.kicad_pcb DST.kicad_pcb
"""
import re

src = open('scripts/route_base.py').read()


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old, src.count(old))
    src = src.replace(old, new)


# 1. keep tracks/vias/zones instead of stripping them
sub('''_keep = []
for t in list(board.GetTracks()):
    _keep.append(t)
    board.RemoveNative(t)
for z in list(board.Zones()):
    _keep.append(z)
    board.RemoveNative(z)
''', '''import os
RIPN = set(x for x in os.environ.get('RIP', '+5V').split(',') if x)
KEEP_T = []
KEEP_V = []
for t in list(board.GetTracks()):
    if t.GetNetname() not in RIPN:
        if t.GetClass() == 'PCB_VIA':
            try:
                dia = mm(t.GetWidth())
            except TypeError:
                dia = mm(t.GetWidth(pcbnew.F_Cu))
            KEEP_V.append((mm(t.GetPosition().x), mm(t.GetPosition().y), dia, mm(t.GetDrill()), t.GetNetCode()))
        else:
            KEEP_T.append((0 if t.GetLayer() == pcbnew.F_Cu else 1,
                           (mm(t.GetStart().x), mm(t.GetStart().y)),
                           (mm(t.GetEnd().x), mm(t.GetEnd().y)), mm(t.GetWidth()), t.GetNetCode()))
    board.RemoveNative(t)
''')

# 2. stamp kept copper into the base obstacle map; stubs only for ripped nets
sub('''base_owner = [o.copy() for o in owner]''', '''RIPC = set(c for c, n in nets.items() if n in RIPN)
for layer, p, q, w, net in KEEP_T:
    stamp_seg(layer, p, q, w, net)
for x, y, dia, drill, net in KEEP_V:
    stamp_hole(x, y, drill / 2)
    for l in (F, B):
        stamp_disc(l, x, y, dia / 2, net)
base_owner = [o.copy() for o in owner]''')
sub("if d.code <= 0 or d.thru or len(by_net.get(d.code, [])) < 2:",
    "if d.code <= 0 or d.thru or d.code not in RIPC or len(by_net.get(d.code, [])) < 2:")

# 3. route only the rip set
sub('''        if code == GND:
            continue
        if len([d for d in pl if not d.skip]) < 2:''', '''        if code == GND or code not in RIPC:
            continue
        if len([d for d in pl if not d.skip]) < 2:''')

# 4. no GND ties / stitching / new zones; write kept copper back
sub('''gf = gnd_ties()
print('GND tie failures:', gf)
ns = stitch()
print('stitching vias:', ns)
''', '''tracks_out[:0] = KEEP_T
vias_out[:0] = KEEP_V
''')
i = src.index('for lyr in LAYER:\n    z = pcbnew.ZONE(board)')
j = src.index('def fill():')
src = src[:i] + src[j:]
open('scripts/reroute_net.py', 'w').write(
    '# GENERATED by scripts/gen_reroute_net.py from scripts/route_base.py -- do not edit\n' + src)
